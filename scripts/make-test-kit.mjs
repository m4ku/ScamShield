// Builds tests/TEST-KIT.md, a manual test sheet, from the same cases the automated runner uses.
// Usage: npm run test:kit

import { readFile, readdir, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const aiDir = new URL("tests/ai/", root);

const ORDER = ["core", "signs", "legit", "tricky", "languages", "injection", "calls", "images", "followup", "api"];
const TITLES = {
  core: ["Core set", "The original 12 messages and 4 pictures from the build plan. The demo uses core-01, core-05 and core-10."],
  signs: ["Each warning sign", "Every one of the 11 signs, two or three ways each. The named sign must appear in the results."],
  legit: ["Real messages (false alarms)", "Ordinary messages that must NOT be called scams. These matter as much as the scams."],
  tricky: ["Tricky and borderline", "Look-alike links, fake order alerts, warnings about scams, hidden scams in long messages."],
  languages: ["Languages", "A scam and a real message in each language, plus messages answered in a different language than they're written in."],
  injection: ["Prompt injection", "Messages that try to give the checker orders. The answer must ignore them."],
  calls: ["Describe a call", "Use the \"Describe a call\" tab for these."],
  followup: ["Follow-up questions", "Run a check first, then ask the question in the \"Questions about this message?\" box. Answers must never call the message safe or repeat its links or numbers."],
  images: ["Screenshots and photos", "Use the \"Add a screenshot\" tab and upload the file from tests/fixtures/."],
  api: ["Input checks (automated only)", "Sent straight to the API by the runner; listed here for reference."],
};
const VERDICT = {
  likely_scam: "Very likely a scam (red)",
  careful: "Be careful (amber)",
  no_signs: "No common warning signs (grey)",
  "error:unreadable": "\"We couldn't read a message in that picture\"",
  "error:bad_input": "Rejected as bad input",
  "error:failed": "\"Something went wrong\" message",
};
const LANG = { en: "English", es: "Español", zh: "中文", vi: "Tiếng Việt", tl: "Tagalog", hi: "हिन्दी", fr: "Français" };
const MODE = { text: "Paste text", call: "Describe a call", image: "Add a screenshot" };

const files = (await readdir(aiDir)).filter((f) => f.endsWith(".json"));
files.sort((a, b) => ORDER.indexOf(a.replace(".json", "")) - ORDER.indexOf(b.replace(".json", "")));

let total = 0;
const sections = [];
for (const f of files) {
  const key = f.replace(".json", "");
  const cases = JSON.parse(await readFile(new URL(f, aiDir), "utf8"));
  total += cases.length;
  const [title, intro] = TITLES[key] ?? [key, ""];
  const lines = [`## ${title}`, "", intro, ""];
  for (const c of cases) {
    if (key === "api") {
      lines.push(`- **${c.id}**: ${c.note}. Expected: ${c.expect.map((e) => VERDICT[e] ?? e).join(" or ")}.`);
      continue;
    }
    if (key === "followup") {
      lines.push(`### ${c.id}`, "", `- **Check first:** ${c.body.check.message}`, `- **Language:** ${LANG[c.body.language]}`, `- **Then ask:** ${c.body.question}`, `- **Why:** ${c.note}`, "");
      continue;
    }
    lines.push(`### ${c.id}`, "");
    lines.push(`- **Tab:** ${MODE[c.mode]} · **Language:** ${LANG[c.language]}`);
    lines.push(`- **Expected:** ${c.expect.map((e) => VERDICT[e] ?? e).join(" or ")}`);
    if (c.mustHave?.length) lines.push(`- **Must flag:** ${c.mustHave.join(", ")}`);
    if (c.mustNotHave?.length) lines.push(`- **Must not flag:** ${c.mustNotHave.join(", ")}`);
    if (c.note) lines.push(`- **Why:** ${c.note}`);
    lines.push("");
    if (c.image) lines.push(`Upload [${c.image}](fixtures/${c.image}).`, "");
    else lines.push("```text", c.text, "```", "");
  }
  sections.push(lines.join("\n"));
}

const header = `# ScamShield test kit

${total} test cases in ${sections.length} sections. The same cases run automatically with \`npm run test:ai\`; this sheet is for checking by hand in the app, on a phone, and in each language.

**How to use it:** pick the language and tab shown, paste the message (or upload the picture), press Check, and compare with **Expected**. For every result, also check:

- The banner never says the message is safe or real.
- Every highlighted phrase is really in the message.
- "Contact the organization using a number or website you already trust" is in the steps.
- Explanations are in the language you picked, and quotes stay in the message's own language.

Do not edit this file by hand: change \`tests/ai/*.json\` and run \`npm run test:kit\`.

## Things only a person can check

- [ ] Paste a message into the empty box: the check starts on its own.
- [ ] Switch language on the result screen: the page text changes; check again to get explanations in the new language.
- [ ] Take a real screenshot of a text on your own phone and upload it; then a photo of a paper letter taken at an angle.
- [ ] Upload an iPhone photo (HEIC): it should work or show "we couldn't open that picture", never hang.
- [ ] Turn off Wi-Fi and press Check: you see "We couldn't connect."
- [ ] Press Check with an empty box, and with a picture tab but no picture: friendly message, box shakes.
- [ ] On a result, tap "I already clicked, replied or paid", then Back: the same result comes back.
- [ ] Tap "Share with family": the share sheet (phone) or "Copied" (computer) appears, and the text makes sense.
- [ ] A native speaker reads one scam result and one real result in each language: clear, calm, correct.
- [ ] Turn on "Reduce motion" in your phone settings: nothing slides or pops.
- [ ] Use the app with the phone's text size set to the largest: nothing overlaps or gets cut off.

`;

await writeFile(new URL("tests/TEST-KIT.md", root), header + sections.join("\n"));
console.log(`Wrote tests/TEST-KIT.md (${total} cases)`);
